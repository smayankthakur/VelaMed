"""
One-page PDF report via reportlab.

Optional: if reportlab is not installed, write_pdf raises ReportlabMissing and
the CLI falls back to the HTML report (which prints to PDF from any browser).

    pip install reportlab
"""


class ReportlabMissing(RuntimeError):
    pass


def _require_reportlab():
    try:
        import reportlab  # noqa: F401
    except ImportError as e:
        raise ReportlabMissing(
            "reportlab is not installed. Run `pip install reportlab`, "
            "or use the HTML report and 'Save as PDF' from your browser."
        ) from e


def write_pdf(result: dict, scored: dict, path: str) -> str:
    _require_reportlab()
    from datetime import datetime, timezone
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib.colors import HexColor
    from reportlab.pdfgen import canvas

    W, H = A4
    c = canvas.Canvas(path, pagesize=A4)
    left = 20 * mm
    right = W - 20 * mm
    y = H - 22 * mm

    blue = HexColor("#0b5cad")
    grey = HexColor("#656d76")
    rule = HexColor("#d0d7de")
    band_col = HexColor(scored["colour"])

    # Header
    c.setFillColor(blue)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(left, y, "VelaMed")
    c.setFillColor(grey)
    c.setFont("Helvetica", 10)
    c.drawString(left, y - 14, "DPDP & security surface check")

    # Score box (top right)
    pct = round(scored["score"] / scored["max"] * 100)
    c.setFillColor(band_col)
    c.setFont("Helvetica-Bold", 26)
    c.drawRightString(right, y - 2, f"{scored['score']}/{scored['max']}")
    c.setFont("Helvetica-Bold", 11)
    c.drawRightString(right, y - 18, f"{scored['band']} · {pct}%")

    y -= 30
    c.setStrokeColor(blue)
    c.setLineWidth(1.5)
    c.line(left, y, right, y)

    # Target
    y -= 22
    c.setFillColor(HexColor("#1f2328"))
    c.setFont("Helvetica-Bold", 13)
    c.drawString(left, y, result["host"])

    # Table header
    y -= 24
    c.setFont("Helvetica", 8)
    c.setFillColor(grey)
    c.drawString(left, y, "CHECK")
    c.drawString(left + 165, y, "WHAT WE SAW")
    c.drawRightString(right, y, "SCORE")
    y -= 6
    c.setStrokeColor(rule)
    c.setLineWidth(0.6)
    c.line(left, y, right, y)

    # Rows, grouped by Security / DPDP
    group = None
    for item in scored["items"]:
        if item["group"] != group:
            group = item["group"]
            gpts = sum(i["points"] for i in scored["items"] if i["group"] == group)
            gmax = sum(i["max"] for i in scored["items"] if i["group"] == group)
            y -= 20
            c.setFillColor(blue)
            c.setFont("Helvetica-Bold", 9)
            c.drawString(left, y, group.upper())
            c.drawRightString(right, y, f"{gpts}/{gmax}")
            y -= 4
            c.setStrokeColor(rule)
            c.line(left, y, right, y)

        y -= 18
        full = item["points"] == item["max"]
        none = item["points"] == 0
        colour = HexColor("#1a7f37") if full else (HexColor("#c0392b") if none else HexColor("#bf8700"))
        mark = "check" if full else ("miss" if none else "part")

        c.setFillColor(HexColor("#1f2328"))
        c.setFont("Helvetica-Bold", 10)
        c.drawString(left, y, item["label"])
        c.setFillColor(HexColor("#424a53"))
        c.setFont("Helvetica", 9)
        note = item["note"]
        if len(note) > 72:
            note = note[:69] + "…"
        c.drawString(left + 165, y, note)
        c.setFillColor(colour)
        c.setFont("Helvetica-Bold", 10)
        c.drawRightString(right, y, f"{item['points']}/{item['max']}")
        c.setStrokeColor(HexColor("#eaeef2"))
        c.line(left, y - 6, right, y - 6)

    # Footer
    y -= 34
    c.setStrokeColor(rule)
    c.line(left, y, right, y)
    y -= 14
    c.setFillColor(grey)
    c.setFont("Helvetica", 8)
    generated = datetime.now(timezone.utc).strftime("%d %b %Y")
    footer = [
        "This is a passive review of the site's public surface, as any visitor's browser would see it —",
        "no scanning, probing or login was performed. The points above are gaps to review, not a legal",
        f"determination of DPDP compliance. Generated by VelaMed on {generated}. Prepared by Sitelytc Digital Media Pvt. Ltd.",
    ]
    for line in footer:
        c.drawString(left, y, line)
        y -= 11

    c.showPage()
    c.save()
    return path
