"""
One-page HTML report — zero dependencies, print-ready (A4).

Open it in any browser and "Save as PDF" for a clean one-pager, or use
report_pdf.py for a generated PDF. This HTML is the canonical layout.
"""

import html
from datetime import datetime, timezone


def _row(item: dict) -> str:
    full = item["points"] == item["max"]
    none = item["points"] == 0
    colour = "#1a7f37" if full else ("#c0392b" if none else "#bf8700")
    mark = "✓" if full else ("✕" if none else "!")
    return f"""
      <tr>
        <td class="chk">{html.escape(item['label'])}</td>
        <td class="mark" style="color:{colour}">{mark}</td>
        <td class="note">{html.escape(item['note'])}</td>
        <td class="pts">{item['points']}/{item['max']}</td>
      </tr>"""


def build_html(result: dict, scored: dict) -> str:
    host = html.escape(result["host"])
    pct = round(scored["score"] / scored["max"] * 100)
    generated = datetime.now(timezone.utc).strftime("%d %b %Y")

    rows, group = [], None
    for item in scored["items"]:
        if item["group"] != group:
            group = item["group"]
            gpts = sum(i["points"] for i in scored["items"] if i["group"] == group)
            gmax = sum(i["max"] for i in scored["items"] if i["group"] == group)
            rows.append(f'<tr class="grp"><td colspan="3">{html.escape(group)}</td>'
                        f'<td class="pts">{gpts}/{gmax}</td></tr>')
        rows.append(_row(item))
    rows = "".join(rows)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>VelaMed report — {host}</title>
<style>
  @page {{ size: A4; margin: 18mm; }}
  * {{ box-sizing: border-box; }}
  body {{ font-family: -apple-system, Segoe UI, Roboto, Helvetica, Arial, sans-serif;
         color: #1f2328; margin: 0; font-size: 13px; line-height: 1.5; }}
  .wrap {{ max-width: 720px; margin: 0 auto; padding: 24px; }}
  .brand {{ font-weight: 700; letter-spacing: .5px; color: #0b5cad; font-size: 18px; }}
  .sub {{ color: #656d76; font-size: 12px; }}
  .head {{ display: flex; justify-content: space-between; align-items: flex-start;
          border-bottom: 2px solid #0b5cad; padding-bottom: 12px; margin-bottom: 20px; }}
  .scorebox {{ text-align: center; border: 1px solid #d0d7de; border-radius: 10px;
              padding: 14px 20px; min-width: 150px; }}
  .score {{ font-size: 34px; font-weight: 700; color: {scored['colour']}; line-height: 1; }}
  .band {{ font-size: 13px; font-weight: 600; color: {scored['colour']}; margin-top: 4px; }}
  .target {{ font-size: 15px; font-weight: 600; margin: 2px 0 14px; }}
  table {{ width: 100%; border-collapse: collapse; }}
  th {{ text-align: left; font-size: 11px; text-transform: uppercase; letter-spacing: .4px;
       color: #656d76; border-bottom: 1px solid #d0d7de; padding: 6px 8px; }}
  td {{ padding: 9px 8px; border-bottom: 1px solid #eaeef2; vertical-align: top; }}
  .chk {{ font-weight: 600; width: 34%; }}
  .mark {{ width: 24px; font-weight: 700; text-align: center; }}
  .note {{ color: #424a53; }}
  .pts {{ text-align: right; white-space: nowrap; font-variant-numeric: tabular-nums; width: 56px; }}
  tr.grp td {{ background: #f6f8fa; font-weight: 700; font-size: 11px; text-transform: uppercase;
              letter-spacing: .5px; color: #0b5cad; padding: 6px 8px; border-bottom: 1px solid #d0d7de; }}
  .foot {{ margin-top: 22px; font-size: 11px; color: #656d76; border-top: 1px solid #eaeef2;
          padding-top: 12px; }}
</style>
</head>
<body>
  <div class="wrap">
    <div class="head">
      <div>
        <div class="brand">VelaMed</div>
        <div class="sub">DPDP &amp; security surface check</div>
      </div>
      <div class="scorebox">
        <div class="score">{scored['score']}<span style="font-size:16px;color:#656d76">/{scored['max']}</span></div>
        <div class="band">{html.escape(scored['band'])} · {pct}%</div>
      </div>
    </div>

    <div class="target">{host}</div>

    <table>
      <thead>
        <tr><th>Check</th><th></th><th>What we saw</th><th style="text-align:right">Score</th></tr>
      </thead>
      <tbody>{rows}
      </tbody>
    </table>

    <div class="foot">
      This is a <strong>passive review</strong> of the site's public surface, as any visitor's
      browser would see it — no scanning, probing, or login was performed. The points above are
      <strong>gaps to review</strong>, not a legal determination of DPDP compliance.
      Generated by VelaMed on {generated}. Prepared by Sitelytc Digital Media Pvt. Ltd.
    </div>
  </div>
</body>
</html>"""


def write_html(result: dict, scored: dict, path: str) -> str:
    with open(path, "w", encoding="utf-8") as f:
        f.write(build_html(result, scored))
    return path
